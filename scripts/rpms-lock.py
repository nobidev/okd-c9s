#!/usr/bin/python3 -I
"""Generate or verify a lock file for RPMs taken from a plain yum repository.

  rpms-lock.py generate REPO_URL PKG [PKG...] > rpms/okd-el9.lock
  rpms-lock.py fetch    LOCKFILE DESTDIR

The lock file is tab separated: name, NEVRA, URL, sha256.
`fetch` downloads every entry, verifies its sha256 and leaves the RPMs in
DESTDIR (existing files with a matching checksum are reused, which makes
the CI cache effective).
"""

import gzip
import hashlib
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

NS = {
    "repo": "http://linux.duke.edu/metadata/repo",
    "common": "http://linux.duke.edu/metadata/common",
    "rpm": "http://linux.duke.edu/metadata/rpm",
}
ARCHES = ("x86_64", "noarch")


def fetch_bytes(url):
    with urllib.request.urlopen(url, timeout=120) as resp:
        return resp.read()


def rpmvercmp(a, b):
    """Minimal rpmvercmp: compare alnum segments like rpm does."""
    seg = re.compile(r"(\d+|[a-zA-Z]+|~|\^)")
    sa, sb = seg.findall(a), seg.findall(b)
    while sa or sb:
        if sa and sa[0] == "~" or sb and sb[0] == "~":
            if not (sa and sa[0] == "~"):
                return 1
            if not (sb and sb[0] == "~"):
                return -1
            sa, sb = sa[1:], sb[1:]
            continue
        if not sa:
            return -1
        if not sb:
            return 1
        x, y = sa.pop(0), sb.pop(0)
        if x.isdigit() and y.isdigit():
            x, y = int(x), int(y)
        elif x.isdigit() != y.isdigit():
            return 1 if x.isdigit() else -1
        if x != y:
            return 1 if x > y else -1
    return 0


def evr_cmp(a, b):
    for field in ("epoch", "version", "release"):
        c = rpmvercmp(a[field], b[field])
        if c:
            return c
    return 0


def primary_packages(repo_url):
    repo_url = repo_url.rstrip("/") + "/"
    repomd = ET.fromstring(fetch_bytes(repo_url + "repodata/repomd.xml"))
    href = None
    for data in repomd.findall("repo:data", NS):
        if data.get("type") == "primary":
            href = data.find("repo:location", NS).get("href")
    if href is None:
        sys.exit("error: no primary metadata in repomd.xml")
    raw = fetch_bytes(repo_url + href)
    if href.endswith(".gz"):
        raw = gzip.decompress(raw)
    elif href.endswith(".zst") or href.endswith(".xz"):
        sys.exit(f"error: unsupported primary compression: {href}")
    root = ET.fromstring(raw)
    for p in root.findall("common:package", NS):
        if p.get("type") != "rpm":
            continue
        ver = p.find("common:version", NS)
        csum = p.find("common:checksum", NS)
        yield {
            "name": p.find("common:name", NS).text,
            "arch": p.find("common:arch", NS).text,
            "epoch": ver.get("epoch") or "0",
            "version": ver.get("ver"),
            "release": ver.get("rel"),
            "sha256": csum.text if csum.get("type") == "sha256" else None,
            "url": repo_url + p.find("common:location", NS).get("href"),
        }


def generate(repo_url, names):
    newest = {}
    for pkg in primary_packages(repo_url):
        if pkg["name"] not in names or pkg["arch"] not in ARCHES:
            continue
        cur = newest.get(pkg["name"])
        if cur is None or evr_cmp(cur, pkg) < 0:
            newest[pkg["name"]] = pkg
    missing = [n for n in names if n not in newest]
    if missing:
        sys.exit(f"error: not found in {repo_url}: {' '.join(missing)}")
    print(f"# Generated by scripts/rpms-lock.py from {repo_url}")
    print("# name\tNEVRA\tURL\tsha256")
    for name in names:
        p = newest[name]
        if not p["sha256"]:
            sys.exit(f"error: {name} has no sha256 checksum in repodata")
        nevra = f"{p['name']}-{p['epoch']}:{p['version']}-{p['release']}.{p['arch']}"
        print(f"{name}\t{nevra}\t{p['url']}\t{p['sha256']}")


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(lockfile, destdir):
    os.makedirs(destdir, exist_ok=True)
    with open(lockfile) as f:
        entries = [l.rstrip("\n").split("\t") for l in f
                   if l.strip() and not l.startswith("#")]
    for name, nevra, url, sha in entries:
        dest = os.path.join(destdir, os.path.basename(url))
        if os.path.exists(dest) and sha256_file(dest) == sha:
            print(f"cached   {nevra}")
            continue
        print(f"download {nevra}")
        tmp = dest + ".part"
        try:
            with urllib.request.urlopen(url, timeout=600) as resp, open(tmp, "wb") as out:
                while True:
                    chunk = resp.read(1 << 20)
                    if not chunk:
                        break
                    out.write(chunk)
        except Exception as e:  # noqa: BLE001 - report and fail loudly
            sys.exit(f"error: cannot download {url}: {e}\n"
                     "hint: the upstream mirror only keeps the newest builds; "
                     "run `make rpms-lock` to re-pin, or restore the CI cache.")
        got = sha256_file(tmp)
        if got != sha:
            os.unlink(tmp)
            sys.exit(f"error: sha256 mismatch for {url}: got {got}, want {sha}")
        os.replace(tmp, dest)
    keep = {os.path.basename(e[2]) for e in entries}
    for stale in set(os.listdir(destdir)) - keep:
        if stale.endswith(".rpm"):
            os.unlink(os.path.join(destdir, stale))


def main():
    if len(sys.argv) >= 4 and sys.argv[1] == "generate":
        generate(sys.argv[2], sys.argv[3:])
    elif len(sys.argv) == 4 and sys.argv[1] == "fetch":
        fetch(sys.argv[2], sys.argv[3])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
